// Detect saved language: URL param > localStorage > default 'it'
(function () {
    var params = new URLSearchParams(window.location.search);
    var langParam = params.get('lang');
    if (langParam && translations[langParam]) {
        localStorage.setItem('siteLang', langParam);
    }

    // Intercept all internal links to carry the current language via ?lang=
    document.addEventListener('click', function (e) {
        var link = e.target.closest('a[href]');
        if (!link) return;
        var href = link.getAttribute('href');
        if (!href || href.startsWith('http') || href.startsWith('mailto:') || href.startsWith('tel:') || href.startsWith('#')) return;
        var lang = localStorage.getItem('siteLang') || 'it';
        if (lang === 'it') return;
        e.preventDefault();
        var url = new URL(href, window.location.href);
        url.searchParams.set('lang', lang);
        window.location.href = url.href;
    });
})();
